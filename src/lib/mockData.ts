function formatWaNumber(raw?: string): string {
  if (!raw) return '+971 50 468 1889';
  const digits = raw.replace(/[^0-9]/g, '');
  if (digits === '971504681889') return '+971 50 468 1889';
  return raw.startsWith('+') ? raw : `+${raw}`;
}

